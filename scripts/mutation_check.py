"""Mutation check: do the unit tests catch deliberate, plausible bugs?  (test-suite verification)

    py -3.10 -m scripts.mutation_check          # about 5 to 10 minutes; needs pytest

For each mutation below, copies src/, scripts/, tests/ and pytest.ini to a temporary folder, makes ONE
small edit to a copy (never to the repository), runs the whole test suite there and records whether
at least one test fails ("caught"). The first four rows are the bugs that survived the old suite in
docs/REVIEW_NOTES.md section 1 (2026-10-12). Writes results/mutation_check.md.

A caught mutation shows that some test is sensitive to that bug; it does not show that the test was
designed for it (look at which test failed). Scaffolding written by the AI (AI_LOG row to add).
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

MUTATIONS = [  # (name, file, original text, mutated text, why it matters)
    ("parallel-axis: drop m2 (lc2e - lc2)^2", "src/dynamics.py",
     "I2_eff = I2 + m2*(lc2_eff - lc2)**2 + m_p*(l2 - lc2_eff)**2",
     "I2_eff = I2 + m_p*(l2 - lc2_eff)**2", "survived in the 2026-10-12 review"),
    ("parallel-axis: drop m_p (l2 - lc2e)^2", "src/dynamics.py",
     "I2_eff = I2 + m2*(lc2_eff - lc2)**2 + m_p*(l2 - lc2_eff)**2",
     "I2_eff = I2 + m2*(lc2_eff - lc2)**2", "survived in the 2026-10-12 review"),
    ("RK4 k2 stage perturbed by 1 % (order drops)", "src/solvers.py",
     "k2 = f(t + h / 2, x + h / 2 * k1)", "k2 = f(t + h / 2, x + 1.01 * h / 2 * k1)", "survived in the 2026-10-12 review"),
    ("phase range halved to [0, pi)", "src/data.py",
     "rng.uniform(0.0, 2 * np.pi, (n, 2))", "rng.uniform(0.0, np.pi, (n, 2))", "survived in the 2026-10-12 review"),
    ("RK4 weights 1-3-1-1 instead of 1-2-2-1 (still consistent, order 1)", "src/solvers.py",
     "h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)", "h / 6 * (k1 + 3 * k2 + k3 + k4)", "a classic transcription error"),
    ("gravity row 2 uses cos(q1)", "src/dynamics.py",
     "g2 = m2e*lc2e*p.g*np.cos(q1 + q2)", "g2 = m2e*lc2e*p.g*np.cos(q1)", "caught before; regression check"),
    ("DeepONet pairs branch channel k with trunk channel 3 - k", "src/model.py",
     'torch.einsum("bkp,btkp->btk", b, k)', 'torch.einsum("bkp,btkp->btk", b.flip(1), k)',
     "shape tests alone cannot see it (REVIEW_NOTES 3.2)"),
    ("loss denominator uses the centred (z-scored) truth", "src/train.py",
     "    size = true + norm.mean / norm.std\n    num = torch.sqrt(diff", "    size = true\n    num = torch.sqrt(diff",
     "the trajectory-size definition of the relative L2"),
    ("consistency check forgets the 1 / T time rescaling", "src/evaluate.py",
     "dq.append(g * std[j] / t_final)", "dq.append(g * std[j])", "dq/dt in the wrong units"),
    ("energy balance with the friction sign flipped", "src/evaluate.py",
     "power = (torque[n].T * qd).sum(axis=1) - p.b * (qd ** 2).sum(axis=1)",
     "power = (torque[n].T * qd).sum(axis=1) + p.b * (qd ** 2).sum(axis=1)", "the energy-balance metric"),
]


def run_suite(folder: Path) -> tuple[bool, list]:
    """Whole suite, no -x: every failing test is listed, so a targeted test is not hidden behind an
    earlier, incidental one (test_benchmark compares against a duplicate of the dynamics and fails first)."""
    r = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-rf"], cwd=folder,
                       capture_output=True, text=True, timeout=1800)
    failed = sorted({ln.split(" ")[1].split("[")[0] for ln in r.stdout.splitlines() if ln.startswith("FAILED")})
    return r.returncode != 0, failed


def main():
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp) / "repo"
        for part in ("src", "scripts", "tests"):
            shutil.copytree(ROOT / part, base / part, ignore=shutil.ignore_patterns("__pycache__"))
        shutil.copy(ROOT / "pytest.ini", base / "pytest.ini")
        bad, msg = run_suite(base)
        assert not bad, f"the unmutated suite fails: {msg}"
        for name, rel, old, new, why in MUTATIONS:
            path = base / rel
            src = path.read_text(encoding="utf-8")
            assert src.count(old) == 1, f"mutation '{name}': pattern found {src.count(old)} times in {rel}"
            path.write_text(src.replace(old, new), encoding="utf-8")
            try:
                caught, failed = run_suite(base)
            finally:
                path.write_text(src, encoding="utf-8")
            rows.append((name, rel, caught, failed, why))
            print(f"{'CAUGHT ' if caught else 'MISSED '} {name}: {failed}")
    L = ["# Mutation check of the unit tests", "",
         "Generated by `scripts/mutation_check.py`: one deliberate bug at a time in a temporary copy, whole suite run, "
         "'caught' = at least one test failed. All failing tests are listed: `test_benchmark` tests compare against a "
         "second, vectorised copy of the dynamics/RK4 (which is not mutated), so they catch almost anything but only "
         "incidentally; the other names show whether a targeted test catches the bug by itself.", "",
         "| mutation | file | caught? | failing tests | why it is in the list |", "|---|---|---|---|---|"]
    for name, rel, caught, failed, why in rows:
        names = ", ".join(f"`{f.split('::')[-1]}`" for f in failed) or "none"
        targeted = [f for f in failed if "test_benchmark" not in f]
        verdict = "yes" if targeted else ("only via test_benchmark" if caught else "**NO**")
        L.append(f"| {name} | `{rel}` | {verdict} | {names} | {why} |")
    n_t = sum(any("test_benchmark" not in f for f in r[3]) for r in rows)
    L += ["", f"{sum(r[2] for r in rows)} of {len(rows)} mutations caught by some test; {n_t} by a test other than the "
          "cross-implementation checks in `test_benchmark.py`."]
    (ROOT / "results" / "mutation_check.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
