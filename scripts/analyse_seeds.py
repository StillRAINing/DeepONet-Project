"""Analyse the seeds batch: is any model gap bigger than seed noise?  Validation split only.

    py -3.10 -m scripts.analyse_seeds [--selected logs/selected.txt] [--no-offgrid]

Reads results/runs.csv (run ``scripts.summarise_runs`` first) and the selected settings written by
the selection rule (one '<model> <input> <lr> <schedule>' per line). Writes results/analysis_seeds.md:
  1. each selected setting as mean +- std over its seeds;
  2. DeepONet-vs-MLP gaps in units of seed spread, and whether the seed ranges overlap;
  3. off-grid-time check on the seed-3001 checkpoints (skipped with --no-offgrid).
It states what the numbers show and what they cannot show; it makes no claim beyond n = 3 seeds.
Never touches the test or OOD splits.
"""
import argparse
import csv
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
METRICS = [("val_loss", "val loss"), ("median", "median"), ("p95", "p95"),
           ("under_10pct", "under 10 %"), ("q2", "q2"), ("consistency", "qdot vs dq/dt")]


def load_rows():
    with open(ROOT / "results" / "runs.csv") as f:
        return [r for r in csv.DictReader(f)
                if r["n_train"] == "7000" and float(r["n_fourier"] or 0) == 0 and float(r["cons_weight"] or 0) == 0]


def setting_rows(rows, model, inp, lr, sched):
    return [r for r in rows if r["model"] == model and r["input"] == inp
            and abs(float(r["lr"]) - float(lr)) < 1e-12 and r["schedule"] == sched]


def stats(rs, m):
    v = np.array([float(r[m]) for r in rs])
    return v.mean(), (v.std(ddof=1) if len(v) > 1 else float("nan")), v


def cell(rs, m):
    mean, sd, _ = stats(rs, m)
    return f"{mean:.4f} +- {sd:.4f}" if len(rs) > 1 else f"{mean:.4f} (1 seed)"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selected", type=Path, default=ROOT / "logs" / "selected.txt")
    ap.add_argument("--no-offgrid", action="store_true")
    args = ap.parse_args()

    rows = load_rows()
    sel = [ln.split() for ln in args.selected.read_text().splitlines() if ln.strip()]
    groups = {(m, i): (lr, s, setting_rows(rows, m, i, lr, s)) for m, i, lr, s in sel}
    out = ["# Seeds analysis (validation split, n = 1500)\n",
           "Generated by `scripts/analyse_seeds.py`. Settings chosen by the selection rule in "
           "`docs/EXPERIMENTS.md` (lowest seed-3001 val loss per model). Mean +- sample std over seeds.\n",
           "## 1. Selected settings\n",
           "| model | input | lr | schedule | seeds | " + " | ".join(n for _, n in METRICS) + " |",
           "|---|---|---|---|---|" + "---|" * len(METRICS)]
    for (m, i), (lr, s, rs) in groups.items():
        out.append(f"| {m} | {i} | {float(lr):g} | {s} | {len(rs)} | " + " | ".join(cell(rs, k) for k, _ in METRICS) + " |")

    out += ["", "## 2. DeepONet vs MLP, in units of seed spread\n",
            "`gap` = DeepONet mean - MLP mean of val loss (positive: MLP better). `spread` = the larger of the two stds. "
            "`overlap`: whether the two seed ranges (min..max) intersect. With 3 seeds a std is itself uncertain, so "
            "read ratios below about 2 as unresolved, not as ties.\n",
            "| DeepONet | MLP | gap | spread | gap / spread | overlap | reading |", "|---|---|---|---|---|---|---|"]
    for (dm, di), (_, _, drs) in [(k, v) for k, v in groups.items() if k[0] == "deeponet"]:
        for (mm, mi), (_, _, mrs) in [(k, v) for k, v in groups.items() if k[0] == "mlp"]:
            dmean, dsd, dv = stats(drs, "val_loss")
            mmean, msd, mv = stats(mrs, "val_loss")
            sds = [x for x in (dsd, msd) if not np.isnan(x)]
            gap, spread = dmean - mmean, (max(sds) if sds else float("nan"))
            ratio = gap / spread if sds and spread > 0 else float("nan")
            overlap = not (dv.min() > mv.max() or mv.min() > dv.max())
            if len(drs) < 2 or len(mrs) < 2:
                reading = "needs more seeds"
            elif not overlap and abs(ratio) >= 2:
                reading = ("MLP better" if gap > 0 else "DeepONet better") + ", beyond seed noise"
            else:
                reading = "unresolved at this many seeds"
            out.append(f"| {dm}/{di} | {mm}/{mi} | {gap:+.4f} | {spread:.4f} | {ratio:+.1f} | "
                       f"{'yes' if overlap else 'no'} | {reading} |")

    if not args.no_offgrid:
        ckpts = [str(ROOT / "checkpoints" / f"{r['run']}.pt")
                 for (_, _, rs) in groups.values() for r in rs if r["seed"] == "3001"]
        out += ["", "## 3. Query times between the training grid points (seed 3001, first 200 val samples)\n",
                "Both families take t as a continuous input, so this checks interpolation in t, not a DeepONet-specific "
                "advantage. Ratio near 1: no loss of accuracy between grid points.\n"]
        res = subprocess.run([sys.executable, "-m", "scripts.offgrid_eval", *ckpts, "--n", "200"],
                             capture_output=True, text=True, cwd=ROOT)
        out.append(res.stdout.split("\n\n", 1)[-1] if res.returncode == 0 else f"offgrid_eval failed:\n{res.stderr[-800:]}")

    out += ["", "## What this can and cannot show\n",
            "- Three seeds change initialisation and batch order only; the data split is the same for all of them.",
            "- Validation numbers were used to choose the settings, so they are slightly optimistic. Test and OOD are untouched.",
            "- Equal parameter counts (about 171k) are not equal effort in other respects (depth, width split, lr grid); "
            "the grid was identical for all four models.",
            "- Nothing here tests the function-input claim. Both input encodings come from the same 6-mode Fourier torque family."]
    path = ROOT / "results" / "analysis_seeds.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    print("\nwrote", path)


if __name__ == "__main__":
    main()
